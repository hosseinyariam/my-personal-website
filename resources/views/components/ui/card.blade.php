{{--
  کارت محتوا.

  ── چرا کل کارت لینک است یا هیچ‌کدام ──
  UI Kit §8.4: «کارت کامل فقط زمانی قابل کلیک باشد که رفتار آن روشن و
  با لینک‌های داخلی متعارض نباشد.» اگر کارت لینک باشد، نباید لینک دیگری
  داخلش باشد؛ وگرنه ناحیه‌های کلیک روی هم می‌افتند و برای صفحه‌خوان
  و صفحه‌کلید مبهم می‌شوند. پس این کامپوننت یک کارت کاملاً لینک است.

  ── چرا $interactive مستقل از $href ──
  کارت غیرلینک هم می‌تواند بازخورد hover بخواهد (مثلاً کارتی که فرم
  درونش است). پس این دو صفت جدا نگه داشته شده‌اند.
--}}
@props([
    'href' => null,
    'interactive' => true,
])

@php
    // فقط وقتی کارت لینک است، hover معنا دارد؛ در غیر این صورت
    // card-interactive صرفاً یک سایه‌ی گمراه‌کننده اضافه می‌کند.
    $classes = 'card'.($interactive ? ' card-interactive' : '');
@endphp

@if ($href)
    <a href="{{ $href }}" {{ $attributes->merge(['class' => $classes]) }}>
        {{ $slot }}
    </a>
@else
    <div {{ $attributes->merge(['class' => $classes]) }}>
        {{ $slot }}
    </div>
@endif
